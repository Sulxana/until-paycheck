/** „აპრილი" → „აპრილში" */
const monthIn = (m: number) => {
  const n = KA_MONTHS_FULL[m]
  return (n.endsWith('ი') ? n.slice(0, -1) : n) + 'ში'
}
const r10 = (v: number) => Math.round(v / 10) * 10

/** რიცხვითი ვარიანტები: სწორი + უნიკალური დისტრაქტორები (სულ 4) */
function numOptions(correct: number, cands: number[], f: (n: number) => string, valid: (n: number) => boolean = () => true): string[] {
  const vals: number[] = [correct]
  for (const c of cands) if (vals.length < 4 && valid(c) && !vals.includes(c)) vals.push(c)
  let k = 1
  while (vals.length < 4) {
    const c = correct + k * (Math.abs(correct) > 50 ? 25 : 3)
    if (valid(c) && !vals.includes(c)) vals.push(c)
    k = k > 0 ? -k : -k + 1
  }
  const strs = vals.map(v => f(v))
  return strs
}

