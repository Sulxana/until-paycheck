function hash(s: string): number {
  let h = 2166136261
  for (let i = 0; i < s.length; i++) { h ^= s.charCodeAt(i); h = Math.imul(h, 16777619) }
  return h >>> 0
}
function rng(seed: number) {
  let a = seed >>> 0
  return () => { a = (a + 0x6d2b79f5) >>> 0; let t = a; t = Math.imul(t ^ (t >>> 15), t | 1); t ^= t + Math.imul(t ^ (t >>> 7), t | 61); return ((t ^ (t >>> 14)) >>> 0) / 4294967296 }
}
/** ვარიანტების დეტერმინისტული არევა (სწორი პასუხის ინდექსი განახლდება) */
export function arrange(item: LessonItem, salt: string): LessonItem {
  const r = rng(hash(item.id + '|' + salt))
  const idx = item.options.map((_, i) => i)
  // „მართალია / მცდარია" და 3-ვარიანტიანი სიები მაინც ირევა
  for (let i = idx.length - 1; i > 0; i--) { const j = Math.floor(r() * (i + 1)); [idx[i], idx[j]] = [idx[j], idx[i]] }
  return { ...item, options: idx.map(i => item.options[i]), correct: idx.indexOf(item.correct) }
}

function resolve(d: LessonDef, c: LessonCtx, kind: 'general' | 'hardship'): LessonItem {
  return { ...d, kind, correct: 0, forYou: d.forYou(c) }
}

export type Slot = 'review' | 'new' | 'own'
export interface MorningSlot { slot: Slot; label: string; item: LessonItem }

const INTERVALS = [1, 3, 7]
/** დონე ათვისებული თემების მიხედვით */
export const levelFor = (topics: number): 1 | 2 | 3 => (topics <= 1 ? 1 : topics <= 3 ? 2 : 3)

function newPool(level: 1 | 2 | 3): LessonDef[] {
  const exact = ALL_GENERAL.filter(d => d.level === level)
  return exact.length >= 8 ? exact : ALL_GENERAL.filter(d => d.level === level || d.level === level - 1)
}
const mod = (a: number, n: number) => ((a % n) + n) % n

/**
 * დილის სამი ერთეული. dayIdx = floor(lessonCursor / 3).
 * review = ერთეული, რომელიც „ახალი" იყო interval დღის წინ (1, 3, 7 — ციკლურად).
 */
export function morningSet(c: LessonCtx, cursor: number, topics: number, hardship: boolean): MorningSlot[] {
  const day = Math.max(0, Math.floor(cursor / 3))
  const interval = INTERVALS[day % INTERVALS.length]
  const salt = `${c.p.id}|${day}`
  if (hardship) {
    const pool = HARD
    const nw = pool[mod(day, pool.length)]
    const rv = pool[mod(day - interval, pool.length)]
    const owns = OWN_HARD.map(t => t(c)).filter((x): x is LessonItem => !!x)
    const ow = owns[mod(day, owns.length)]
    return [
      { slot: 'review', label: 'გამეორება', item: arrange(resolve(rv, c, 'hardship'), salt) },
      { slot: 'new', label: 'ერთი ნაბიჯი', item: arrange(resolve(nw, c, 'hardship'), salt) },
      { slot: 'own', label: 'შენი რიცხვები', item: arrange(ow, salt) },
    ]
  }
  const level = levelFor(topics)
  const pool = newPool(level)
  const nw = pool[mod(day, pool.length)]
  const rv = pool[mod(day - interval, pool.length)]
  const owns = OWN.map(t => t(c)).filter((x): x is LessonItem => !!x)
  const ow = owns[mod(day, owns.length)]
  const dots = '●'.repeat(nw.level) + '○'.repeat(3 - nw.level)
  return [
    { slot: 'review', label: `გამეორება · ნასწავლი ${interval} დღის წინ`, item: arrange(resolve(rv, c, 'general'), salt) },
    { slot: 'new', label: `ახალი · სირთულე ${dots}`, item: arrange(resolve(nw, c, 'general'), salt) },
    { slot: 'own', label: 'შენი რიცხვები', item: arrange(ow, salt) },
  ]
}

/** საღამოს „გაიხსენე": დილის ახალი ერთეული (ან, თუ დილა ჯერ არ გაგივლია, დღევანდელი გამეორება), სხვა რიგით */
export function eveningRecall(c: LessonCtx, cursor: number, topics: number, hardship: boolean, morningDone: boolean): LessonItem {
  const base = morningDone ? Math.max(0, cursor - 3) : cursor
  const set = morningSet(c, base, topics, hardship)
  const pick = morningDone ? set[1].item : set[0].item
  return arrange(pick, `evening|${c.p.id}|${base}`)
}

